def _coerce_point(pt: PointInput) -> spg.Point:
    """Convert a ``(x, y)`` tuple or :class:`~sympy.geometry.point.Point` into an exact ``Point``."""
    if isinstance(pt, spg.Point):
        return pt
    return spg.Point(sp.sympify(pt[0]), sp.sympify(pt[1]))


def _add_line(
    model: Model,
    pt_1: spg.Point,
    pt_2: spg.Point,
    *,
    classes: list[str] | None = None,
    line_id: str = "",
    guide: bool = False,
) -> spg.Line:
    """Register a line in ``model`` without triggering unintentional cross-pool intersections."""
    cls_list = list(classes) if classes else []
    constructed = model.construct_line(pt_1, pt_2, classes=cls_list, ID=line_id, guide=True)
    if constructed is None:
        _, existing = check_existence(model, spg.Line(pt_1, pt_2), model.lines)
        if existing is None or not isinstance(existing, spg.Line):
            raise RuntimeError("Expected existing line in model after duplicate construct_line.")
        line_obj = existing
    else:
        line_obj = constructed

    if not guide:
        model[line_obj].guide = False
    return line_obj


def _register_intersection_point(
    model: Model,
    pt: spg.Point,
    line_1: spg.Line,
    line_2: spg.Line,
    *,
    classes: list[str] | None = None,
    pt_id: str = "",
    guide: bool = False,
) -> spg.Point:
    """Register an exact line-line intersection in ``model`` and link parent incidences."""
    pt_model = model.set_point(
        pt.x,
        pt.y,
        parents=[line_1, line_2],
        classes=list(classes) if classes else [],
        ID=pt_id,
        guide=guide,
    )
    model[line_1].parents[pt_model] = ""
    model[line_2].parents[pt_model] = ""
    return pt_model


def _discover_remaining_intersections(
    model: Model,
    *,
    prefix: str = "X",
) -> list[spg.Point]:
    """Compute all pairwise intersections of non-guide lines in ``model`` in-process."""
    active_lines = [ln for ln in model.lines if not model[ln].guide]
    added: list[spg.Point] = []
    used_ids = {model[p].ID for p in model.points if model[p].ID}
    counter = 1

    for l1, l2 in combinations(active_lines, 2):
        meet = exact_line_meet(l1, l2)
        if meet is None:
            continue
        if meet in model.points:
            model[meet].parents[l1] = ""
            model[meet].parents[l2] = ""
            model[l1].parents[meet] = ""
            model[l2].parents[meet] = ""
            continue
        while f"{prefix}{counter}" in used_ids:
            counter += 1
        new_id = f"{prefix}{counter}"
        used_ids.add(new_id)
        counter += 1
        pt_new = _register_intersection_point(
            model,
            meet,
            l1,
            l2,
            classes=["intersection"],
            pt_id=new_id,
        )
        added.append(pt_new)

    return added


def permutation_parity(perm: Sequence[int]) -> str:
    r"""Return ``"even"`` or ``"odd"`` for a permutation of ``(0, 1, 2)``.

    Args:
        perm: Three-element sequence permuting ``(0, 1, 2)``.

    Returns:
        ``"even"`` if the inversion count is even ($\sigma \in A_3$), else ``"odd"``.

    Raises:
        ValueError: If ``perm`` is not a permutation of ``(0, 1, 2)``.
    """
    if sorted(perm) != [0, 1, 2]:
        raise ValueError(f"Expected a permutation of (0, 1, 2); got {perm!r}.")
    inversions = sum(
        1 for i in range(3) for j in range(i + 1, 3) if perm[i] > perm[j]
    )
    return "even" if inversions % 2 == 0 else "odd"


def get_preset(name: str = "hexagon") -> PresetConfig:
    """Look up a named exact coordinate preset from :data:`PRESETS`.

    Args:
        name: Preset key (``"hexagon"``, ``"parallel"``, ``"steiner"``, ``"harmonic"``, ``"golden"``).

    Returns:
        Corresponding :class:`PresetConfig`.

    Raises:
        KeyError: If ``name`` is not a known preset.
    """
    if name not in PRESETS:
        valid = ", ".join(sorted(PRESETS))
        raise KeyError(f"Unknown preset {name!r}. Available presets: {valid}.")
    return PRESETS[name]


def _validate_carrier_triples(
    a_pts: tuple[spg.Point, spg.Point, spg.Point],
    b_pts: tuple[spg.Point, spg.Point, spg.Point],
) -> None:
    """Ensure $(A_0, A_1, A_2)$ and $(B_0, B_1, B_2)$ lie on two distinct lines."""
    if len({a_pts[0], a_pts[1], a_pts[2]}) < 3:
        raise ValueError("Points A0, A1, A2 must be pairwise distinct.")
    if len({b_pts[0], b_pts[1], b_pts[2]}) < 3:
        raise ValueError("Points B0, B1, B2 must be pairwise distinct.")
    if not spg.Point.is_collinear(*a_pts):
        raise ValueError("Points A0, A1, A2 must be collinear.")
    if not spg.Point.is_collinear(*b_pts):
        raise ValueError("Points B0, B1, B2 must be collinear.")
    line_a = spg.Line(a_pts[0], a_pts[2])
    line_b = spg.Line(b_pts[0], b_pts[2])
    if line_a.equals(line_b):
        raise ValueError("Carrier lines a and b must be distinct.")


def construct_pappus_hexagon(
    model: Model | None = None,
    a_points: Sequence[PointInput] | None = None,
    b_points: Sequence[PointInput] | None = None,
    perm: Sequence[int] = (0, 1, 2),
    *,
    preset: str = "hexagon",
    include_apex: bool = True,
    include_hexagon: bool = True,
    include_type_triangles: bool = False,
    discover_all_intersections: bool = False,
) -> PappusHexagonResult:
    r"""Construct Pappus's Hexagon Theorem for a single permutation $\sigma \in S_3$.

    Given collinear triples $(A_0, A_1, A_2)$ on line $a$ and $(B_0, B_1, B_2)$ on
    line $b$, pairs vertices according to $\sigma = (\sigma_0, \sigma_1, \sigma_2)$
    to form the hexagon $(A_0, B_{\sigma_1}, A_2, B_{\sigma_0}, A_1, B_{\sigma_2})$
    and constructs the three opposite-side cross-join meets:

    - $M_{01} = [A_0 B_{\sigma_1}] \cap [A_1 B_{\sigma_0}]$
    - $M_{12} = [A_1 B_{\sigma_2}] \cap [A_2 B_{\sigma_1}]$
    - $M_{20} = [A_2 B_{\sigma_0}] \cap [A_0 B_{\sigma_2}]$

    Handles both intersecting carrier lines (*Synagoge* VII.139) and parallel
    carrier lines (*Synagoge* VII.138), as well as configurations where one pair
    of opposite cross-joins is parallel (meeting on the projective line at infinity).

    Args:
        model: Optional existing :class:`~geometor.model.Model`; created if ``None``.
        a_points: Optional sequence of 3 points on line $a$; defaults to ``preset``.
        b_points: Optional sequence of 3 points on line $b$; defaults to ``preset``.
        perm: Permutation of ``(0, 1, 2)`` ordering the $B$-points.
        preset: Preset key used when ``a_points`` or ``b_points`` is ``None``.
        include_apex: If True and $a \nparallel b$, add $O = a \cap b$ to ``model``.
        include_hexagon: If True, register the 6-cycle hexagon polygon in ``model``.
        include_type_triangles: If True, construct the ``square``, ``circle``, and
            ``diamond`` triangles reviving GEOMETOR's ``pappus-3.py`` exploration.
        discover_all_intersections: If True, add all remaining line-line intersections.

    Returns:
        Populated :class:`PappusHexagonResult`.
    """
    parity = permutation_parity(perm)
    perm_tuple: Perm3 = (int(perm[0]), int(perm[1]), int(perm[2]))

    cfg = get_preset(preset)
    raw_a = tuple(_coerce_point(p) for p in a_points) if a_points is not None else cfg.a_points
    raw_b = tuple(_coerce_point(p) for p in b_points) if b_points is not None else cfg.b_points
    if len(raw_a) != 3 or len(raw_b) != 3:
        raise ValueError("Both a_points and b_points must contain exactly 3 points.")

    a_triple = (raw_a[0], raw_a[1], raw_a[2])
    b_triple = (raw_b[0], raw_b[1], raw_b[2])
    _validate_carrier_triples(a_triple, b_triple)

    if model is None:
        model = Model(f"pappus_{preset}_{''.join(map(str, perm_tuple))}")

    model_a = tuple(
        model.set_point(
            pt.x,
            pt.y,
            classes=["given", "A", TYPE_NAMES[idx]],
            ID=f"A{idx}",
        )
        for idx, pt in enumerate(a_triple)
    )
    # Assign type classes on B according to the active pairing B_{perm[idx]} <-> TYPE_NAMES[idx]
    inv_type: dict[int, str] = {perm_tuple[idx]: TYPE_NAMES[idx] for idx in range(3)}
    model_b = tuple(
        model.set_point(
            pt.x,
            pt.y,
            classes=["given", "B", inv_type[idx]],
            ID=f"B{idx}",
        )
        for idx, pt in enumerate(b_triple)
    )

    line_a = _add_line(
        model,
        model_a[0],
        model_a[2],
        classes=["given", "carrier", "line_a"],
        line_id="[ A0 A2 ]",
    )
    line_b = _add_line(
        model,
        model_b[0],
        model_b[2],
        classes=["given", "carrier", "line_b"],
        line_id="[ B0 B2 ]",
    )
    # Ensure middle carrier points record parent incidence with their carrier lines
    model[model_a[1]].parents[line_a] = ""
    model[line_a].parents[model_a[1]] = ""
    model[model_b[1]].parents[line_b] = ""
    model[line_b].parents[model_b[1]] = ""

    apex_pt: spg.Point | None = exact_line_meet(line_a, line_b)
    if apex_pt is not None and include_apex:
        apex_pt = _register_intersection_point(
            model,
            apex_pt,
            line_a,
            line_b,
            classes=["apex"],
            pt_id="O",
        )

    b_perm = (
        model_b[perm_tuple[0]],
        model_b[perm_tuple[1]],
        model_b[perm_tuple[2]],
    )

    # Construct the 6 cross-join lines for the three opposite pairs:
    # pair (0, 1) -> missing 2 (diamond); pair (1, 2) -> missing 0 (square); pair (2, 0) -> missing 1 (circle)
    pair_specs: tuple[tuple[str, int, int, int], ...] = (
        ("M01", 0, 1, 2),
        ("M12", 1, 2, 0),
        ("M20", 2, 0, 1),
    )
    cross_lines: dict[tuple[int, int], spg.Line] = {}
    meets: dict[str, spg.Point | None] = {}

    for meet_id, u, v, missing_idx in pair_specs:
        b_idx_v = perm_tuple[v]
        b_idx_u = perm_tuple[u]
        ln_uv = _add_line(
            model,
            model_a[u],
            model_b[b_idx_v],
            classes=["cross", f"pair_{meet_id.lower()}"],
            line_id=f"[ A{u} B{b_idx_v} ]",
        )
        ln_vu = _add_line(
            model,
            model_a[v],
            model_b[b_idx_u],
            classes=["cross", f"pair_{meet_id.lower()}"],
            line_id=f"[ A{v} B{b_idx_u} ]",
        )
        cross_lines[(u, b_idx_v)] = ln_uv
        cross_lines[(v, b_idx_u)] = ln_vu

        pt_meet = exact_line_meet(ln_uv, ln_vu)
        if pt_meet is not None:
            pt_meet = _register_intersection_point(
                model,
                pt_meet,
                ln_uv,
                ln_vu,
                classes=["meet", parity, TYPE_NAMES[missing_idx]],
                pt_id=meet_id,
            )
        meets[meet_id] = pt_meet

    finite_meets = [pt for pt in (meets["M01"], meets["M12"], meets["M20"]) if pt is not None]
    if len(finite_meets) < 2:
        raise ValueError(
            "At least two cross-join pairs are parallel; Pappus line lies at infinity "
            "(affine translation/scaling case where all three meets are ideal points)."
        )

    pappus_line = _add_line(
        model,
        finite_meets[0],
        finite_meets[1],
        classes=["pappus", parity],
    )
    for pt_m in finite_meets:
        model[pt_m].parents[pappus_line] = ""
        model[pappus_line].parents[pt_m] = ""

    if len(finite_meets) == 3:
        is_col = bool(spg.Point.is_collinear(*finite_meets))
    else:
        # One cross-join pair is parallel: verify Pappus line is parallel to that pair!
        missing_key = next(k for k, v in meets.items() if v is None)
        idx_map = {"M01": (0, perm_tuple[1]), "M12": (1, perm_tuple[2]), "M20": (2, perm_tuple[0])}
        parallel_cross = cross_lines[idx_map[missing_key]]
        is_col = exact_line_meet(pappus_line, parallel_cross) is None

    hexagon_poly: spg.Polygon | None = None
    if include_hexagon:
        hex_vertices = [
            model_a[0],
            b_perm[1],
            model_a[2],
            b_perm[0],
            model_a[1],
            b_perm[2],
        ]
        hexagon_poly = model.set_polygon(hex_vertices, classes=["hexagon", parity])

    type_triangles: dict[str, spg.Polygon] = {}
    if include_type_triangles:
        tri_specs = (
            ("square", model_a[0], b_perm[0], meets["M12"]),
            ("circle", model_a[1], b_perm[1], meets["M20"]),
            ("diamond", model_a[2], b_perm[2], meets["M01"]),
        )
        for t_name, p_a, p_b, p_m in tri_specs:
            if p_m is not None and not spg.Point.is_collinear(p_a, p_b, p_m):
                poly = model.set_polygon([p_a, p_b, p_m], classes=["triangle", t_name])
                if isinstance(poly, spg.Polygon):
                    type_triangles[t_name] = poly

    if discover_all_intersections:
        _discover_remaining_intersections(model)

    return PappusHexagonResult(
        model=model,
        perm=perm_tuple,
        parity=parity,
        a_points=(model_a[0], model_a[1], model_a[2]),
        b_points=(model_b[0], model_b[1], model_b[2]),
        b_permuted=b_perm,
        line_a=line_a,
        line_b=line_b,
        apex=apex_pt,
        cross_lines=cross_lines,
        meets=meets,
        pappus_line=pappus_line,
        hexagon=hexagon_poly,
        type_triangles=type_triangles,
        is_collinear=is_col,
    )


def construct_pappus_configuration(
    model: Model | None = None,
    a_points: Sequence[PointInput] | None = None,
    b_points: Sequence[PointInput] | None = None,
    *,
    preset: str = "steiner",
    include_apex: bool = True,
    discover_all_intersections: bool = False,
    scan_harmonics: bool = True,
    enable_divine: bool = False,
) -> PappusConfigurationResult:
    r"""Construct the complete $S_3$ six-permutation Pappus–Steiner configuration.

    Generates all 9 cross-join lines $[A_i B_j]$, all 18 cross-join meets ``M{i1}{j1}{i2}{j2}``,
    all 6 Pappus lines ($3$ even in $A_3$ and $3$ odd in $S_3 \setminus A_3$), and
    constructs the two **Steiner (Star) points**:

    - :math:`S_+` (ID ``"S1"``): common concurrency point of the 3 even Pappus lines.
    - :math:`S_-` (ID ``"S2"``): common concurrency point of the 3 odd Pappus lines.

    Also constructs the Steiner line :math:`[S_+ S_-]` when both star points are finite
    and distinct, and scans the resulting configuration for collinear harmonic
    ranges and golden sections.

    Args:
        model: Optional existing :class:`~geometor.model.Model`; created if ``None``.
        a_points: Optional sequence of 3 points on line $a$; defaults to ``preset``.
        b_points: Optional sequence of 3 points on line $b$; defaults to ``preset``.
        preset: Preset key used when ``a_points`` or ``b_points`` is ``None``.
        include_apex: If True and $a \nparallel b$, add $O = a \cap b$ to ``model``.
        discover_all_intersections: If True, register all pairwise intersections of
            carrier lines, cross-lines, and Pappus lines in ``model``.
        scan_harmonics: If True, populate ``harmonic_ranges`` via :func:`find_harmonic_ranges`.
        enable_divine: If True, attach :mod:`geometor.divine` hook and scan golden sections.

    Returns:
        Populated :class:`PappusConfigurationResult`.
    """
    cfg = get_preset(preset)
    raw_a = tuple(_coerce_point(p) for p in a_points) if a_points is not None else cfg.a_points
    raw_b = tuple(_coerce_point(p) for p in b_points) if b_points is not None else cfg.b_points
    if len(raw_a) != 3 or len(raw_b) != 3:
        raise ValueError("Both a_points and b_points must contain exactly 3 points.")

    a_triple = (raw_a[0], raw_a[1], raw_a[2])
    b_triple = (raw_b[0], raw_b[1], raw_b[2])
    _validate_carrier_triples(a_triple, b_triple)

    if model is None:
        model = Model(f"pappus_configuration_{preset}")
    if enable_divine:
        enable_divine_analysis(model)

    model_a = tuple(
        model.set_point(pt.x, pt.y, classes=["given", "A"], ID=f"A{idx}")
        for idx, pt in enumerate(a_triple)
    )
    model_b = tuple(
        model.set_point(pt.x, pt.y, classes=["given", "B"], ID=f"B{idx}")
        for idx, pt in enumerate(b_triple)
    )

    line_a = _add_line(
        model,
        model_a[0],
        model_a[2],
        classes=["given", "carrier", "line_a"],
        line_id="[ A0 A2 ]",
    )
    line_b = _add_line(
        model,
        model_b[0],
        model_b[2],
        classes=["given", "carrier", "line_b"],
        line_id="[ B0 B2 ]",
    )
    model[model_a[1]].parents[line_a] = ""
    model[line_a].parents[model_a[1]] = ""
    model[model_b[1]].parents[line_b] = ""
    model[line_b].parents[model_b[1]] = ""

    apex_pt: spg.Point | None = exact_line_meet(line_a, line_b)
    if apex_pt is not None and include_apex:
        apex_pt = _register_intersection_point(
            model,
            apex_pt,
            line_a,
            line_b,
            classes=["apex"],
            pt_id="O",
        )

    # All 9 cross-join lines [A_i B_j]
    cross_lines: dict[tuple[int, int], spg.Line] = {}
    for i in range(3):
        for j in range(3):
            cross_lines[(i, j)] = _add_line(
                model,
                model_a[i],
                model_b[j],
                classes=["cross"],
                line_id=f"[ A{i} B{j} ]",
            )

    meets_by_perm: dict[Perm3, tuple[spg.Point | None, spg.Point | None, spg.Point | None]] = {}
    all_meets: dict[str, spg.Point] = {}
    pappus_lines: dict[Perm3, spg.Line] = {}
    even_lines: list[spg.Line] = []
    odd_lines: list[spg.Line] = []

    for perm_idx, perm in enumerate(PERMUTATIONS_S3):
        parity = permutation_parity(perm)
        perm_meets: list[spg.Point | None] = []
        for u, v in ((0, 1), (1, 2), (2, 0)):
            i1, j1 = u, perm[v]
            i2, j2 = v, perm[u]
            # Canonicalize so i1 < i2 for unique alphanumeric ID M{i1}{j1}{i2}{j2}
            if i1 > i2:
                i1, j1, i2, j2 = i2, j2, i1, j1
            meet_id = f"M{i1}{j1}{i2}{j2}"
            ln_1 = cross_lines[(i1, j1)]
            ln_2 = cross_lines[(i2, j2)]
            pt_m = exact_line_meet(ln_1, ln_2)
            if pt_m is not None:
                pt_m = _register_intersection_point(
                    model,
                    pt_m,
                    ln_1,
                    ln_2,
                    classes=["meet", parity, f"perm_{perm_idx}"],
                    pt_id=meet_id,
                )
                all_meets[meet_id] = pt_m
            perm_meets.append(pt_m)

        meets_tuple = (perm_meets[0], perm_meets[1], perm_meets[2])
        meets_by_perm[perm] = meets_tuple

        finite_m = [p for p in meets_tuple if p is not None]
        if len(finite_m) < 2:
            raise ValueError(f"Permutation {perm} has fewer than two finite cross-join meets.")
        p_line = _add_line(
            model,
            finite_m[0],
            finite_m[1],
            classes=["pappus", parity, f"pappus_{perm_idx}"],
        )
        for p in finite_m:
            model[p].parents[p_line] = ""
            model[p_line].parents[p] = ""
        pappus_lines[perm] = p_line
        if parity == "even":
            even_lines.append(p_line)
        else:
            odd_lines.append(p_line)

    # Verify and construct the two Steiner (Star) 3-fold concurrency points
    steiner_even: spg.Point | None = exact_line_meet(even_lines[0], even_lines[1])
    if steiner_even is not None:
        if not even_lines[2].contains(steiner_even):
            raise AssertionError("Steiner theorem violation: third even Pappus line missed S+.")
        steiner_even = _register_intersection_point(
            model,
            steiner_even,
            even_lines[0],
            even_lines[1],
            classes=["steiner", "star", "even"],
            pt_id="S1",
        )
        model[steiner_even].parents[even_lines[2]] = ""
        model[even_lines[2]].parents[steiner_even] = ""

    steiner_odd: spg.Point | None = exact_line_meet(odd_lines[0], odd_lines[1])
    if steiner_odd is not None:
        if not odd_lines[2].contains(steiner_odd):
            raise AssertionError("Steiner theorem violation: third odd Pappus line missed S-.")
        steiner_odd = _register_intersection_point(
            model,
            steiner_odd,
            odd_lines[0],
            odd_lines[1],
            classes=["steiner", "star", "odd"],
            pt_id="S2",
        )
        model[steiner_odd].parents[odd_lines[2]] = ""
        model[odd_lines[2]].parents[steiner_odd] = ""

    steiner_line: spg.Line | None = None
    if steiner_even is not None and steiner_odd is not None and not steiner_even.equals(steiner_odd):
        steiner_line = _add_line(
            model,
            steiner_even,
            steiner_odd,
            classes=["steiner", "steiner_line"],
            line_id="[ S1 S2 ]",
        )

    if discover_all_intersections:
        _discover_remaining_intersections(model)

    harmonics = find_harmonic_ranges(model) if scan_harmonics else []
    goldens = find_golden_sections(model, register_sections=enable_divine) if enable_divine else []

    return PappusConfigurationResult(
        model=model,
        a_points=(model_a[0], model_a[1], model_a[2]),
        b_points=(model_b[0], model_b[1], model_b[2]),
        line_a=line_a,
        line_b=line_b,
        apex=apex_pt,
        cross_lines=cross_lines,
        meets_by_perm=meets_by_perm,
        all_meets=all_meets,
        pappus_lines=pappus_lines,
        even_pappus_lines=(even_lines[0], even_lines[1], even_lines[2]),
        odd_pappus_lines=(odd_lines[0], odd_lines[1], odd_lines[2]),
        steiner_even=steiner_even,
        steiner_odd=steiner_odd,
        steiner_line=steiner_line,
        harmonic_ranges=harmonics,
        golden_sections=goldens,
    )


def construct_harmonic_fourth(
    model: Model | None = None,
    pt_a: PointInput = (0, 0),
    pt_b: PointInput = (4, 0),
    pt_c: PointInput = (sp.Rational(4, 3), 0),
    *,
    apex: PointInput | None = None,
    relay: PointInput | None = None,
) -> HarmonicFourthResult:
    r"""Construct the fourth harmonic conjugate $D$ of $C$ with respect to $(A, B)$ by straightedge alone.

    Executes the classical **complete quadrilateral** construction (already implicit
    in Pappus's *Synagoge* Book VII harmonic lemmas):

    1. Choose an auxiliary apex $P$ not on $[A B]$ and join $[P A]$, $[P B]$, $[P C]$.
    2. Choose an auxiliary relay point $Q$ on $[P C]$ distinct from $P$ and $C$.
    3. Draw $[A Q]$ to meet $[P B]$ at $R$, and draw $[B Q]$ to meet $[P A]$ at $S$.
    4. Draw the diagonal $[R S]$; its intersection $D = [R S] \cap [A B]$ satisfies
       $(A, B; C, D) = -1$ **independently** of the choices of $P$ and $Q$.

    Args:
        model: Optional existing :class:`~geometor.model.Model`; created if ``None``.
        pt_a: First base point $A$.
        pt_b: Second base point $B$.
        pt_c: Third collinear point $C$ (distinct from $A$, $B$, and the midpoint of $AB$).
        apex: Optional off-line apex $P$; chosen automatically with clean exact coordinates if ``None``.
        relay: Optional point $Q$ on $[P C]$; defaults to the exact midpoint of $P$ and $C$.

    Returns:
        Populated :class:`HarmonicFourthResult`.

    Raises:
        ValueError: If $A, B, C$ are invalid or if $C$ is the Euclidean midpoint of $AB$.
    """
    a_in = _coerce_point(pt_a)
    b_in = _coerce_point(pt_b)
    c_in = _coerce_point(pt_c)

    if a_in.equals(b_in) or c_in.equals(a_in) or c_in.equals(b_in):
        raise ValueError("Points A, B, C must be pairwise distinct.")
    if not spg.Point.is_collinear(a_in, b_in, c_in):
        raise ValueError("Points A, B, C must be collinear.")

    base_test = spg.Line(a_in, b_in)
    if apex is None:
        # Offset perpendicular to AB from the midpoint of A and B for a balanced quadrilateral
        dx = b_in.x - a_in.x
        dy = b_in.y - a_in.y
        mx = (a_in.x + b_in.x) / 2
        my = (a_in.y + b_in.y) / 2
        p_in = spg.Point(mx - dy / 2, my + dx / 2 + (sp.Integer(1) if dy == 0 and dx == 0 else sp.Integer(0)))
        if base_test.contains(p_in):
            p_in = spg.Point(a_in.x, a_in.y + 3)
    else:
        p_in = _coerce_point(apex)
        if base_test.contains(p_in):
            raise ValueError("Apex P must not lie on line [A B].")

    line_pc_test = spg.Line(p_in, c_in)
    if relay is None:
        q_in = spg.Point((p_in.x + c_in.x) / 2, (p_in.y + c_in.y) / 2)
    else:
        q_in = _coerce_point(relay)
        if q_in.equals(p_in) or q_in.equals(c_in) or not line_pc_test.contains(q_in):
            raise ValueError("Relay point Q must lie on line [P C] and be distinct from P and C.")

    if model is None:
        model = Model("harmonic_fourth")

    m_a = model.set_point(a_in.x, a_in.y, classes=["given", "base"], ID="A")
    m_b = model.set_point(b_in.x, b_in.y, classes=["given", "base"], ID="B")
    m_c = model.set_point(c_in.x, c_in.y, classes=["given", "conjugate"], ID="C")
    base_line = _add_line(model, m_a, m_b, classes=["given", "carrier"], line_id="[ A B ]")
    model[m_c].parents[base_line] = ""
    model[base_line].parents[m_c] = ""

    m_p = model.set_point(p_in.x, p_in.y, classes=["auxiliary", "apex"], ID="P")
    ln_pa = _add_line(model, m_p, m_a, classes=["quadrilateral"], line_id="[ P A ]")
    ln_pb = _add_line(model, m_p, m_b, classes=["quadrilateral"], line_id="[ P B ]")
    ln_pc = _add_line(model, m_p, m_c, classes=["quadrilateral", "diagonal"], line_id="[ P C ]")

    m_q = model.set_point(q_in.x, q_in.y, parents=[ln_pc], classes=["auxiliary", "relay"], ID="Q")
    model[ln_pc].parents[m_q] = ""

    ln_aq = _add_line(model, m_a, m_q, classes=["cross"], line_id="[ A Q ]")
    ln_bq = _add_line(model, m_b, m_q, classes=["cross"], line_id="[ B Q ]")

    r_pt = exact_line_meet(ln_aq, ln_pb)
    s_pt = exact_line_meet(ln_bq, ln_pa)
    if r_pt is None or s_pt is None:
        raise ValueError("Degenerate auxiliary choice produced parallel quadrilateral sides.")

    m_r = _register_intersection_point(model, r_pt, ln_aq, ln_pb, classes=["meet"], pt_id="R")
    m_s = _register_intersection_point(model, s_pt, ln_bq, ln_pa, classes=["meet"], pt_id="S")

    conj_line = _add_line(
        model,
        m_r,
        m_s,
        classes=["harmonic", "conjugate_line"],
        line_id="[ R S ]",
    )
    d_pt = exact_line_meet(conj_line, base_line)
    if d_pt is None:
        raise ValueError("C is the midpoint of AB; line [R S] is parallel to [A B] (D at infinity).")

    m_d = _register_intersection_point(
        model,
        d_pt,
        conj_line,
        base_line,
        classes=["harmonic", "fourth_harmonic"],
        pt_id="D",
    )

    return HarmonicFourthResult(
        model=model,
        pt_a=m_a,
        pt_b=m_b,
        pt_c=m_c,
        pt_d=m_d,
        apex=m_p,
        relay=m_q,
        diag_r=m_r,
        diag_s=m_s,
        base_line=base_line,
        conjugate_line=conj_line,
    )


def verify_pappus_symbolic() -> sp.Expr:
    r"""Prove Pappus's Hexagon Theorem universally over a symbolic function field.

    Parameterizes carrier line $a$ as $y = 0$ with $A_i = (a_i, 0)$ and carrier
    line $b$ as $y = m x + c$ with $B_j = (b_j, m b_j + c)$ over eight independent
    symbolic indeterminates $(a_0, a_1, a_2, b_0, b_1, b_2, m, c)$ (covering both
    intersecting lines $m \ne 0$ and parallel lines $m = 0, c \ne 0$). Computes the
    homogeneous coordinates of $M_{01}, M_{12}, M_{20}$ and simplifies their $3 \times 3$
    collinearity determinant, confirming it vanishes identically ($0$).

    Returns:
        Simplified determinant expression (identically ``sp.Integer(0)``).
    """
    a0, a1, a2, b0, b1, b2, m, c = sp.symbols("a0 a1 a2 b0 b1 b2 m c")
    pts_a = [(a0, sp.Integer(0), sp.Integer(1)), (a1, sp.Integer(0), sp.Integer(1)), (a2, sp.Integer(0), sp.Integer(1))]
    pts_b = [(b0, m * b0 + c, sp.Integer(1)), (b1, m * b1 + c, sp.Integer(1)), (b2, m * b2 + c, sp.Integer(1))]

    def _cross3(
        u: tuple[sp.Expr, sp.Expr, sp.Expr],
        v: tuple[sp.Expr, sp.Expr, sp.Expr],
    ) -> tuple[sp.Expr, sp.Expr, sp.Expr]:
        return (
            sp.expand(u[1] * v[2] - u[2] * v[1]),
            sp.expand(u[2] * v[0] - u[0] * v[2]),
            sp.expand(u[0] * v[1] - u[1] * v[0]),
        )

    m01 = _cross3(_cross3(pts_a[0], pts_b[1]), _cross3(pts_a[1], pts_b[0]))
    m12 = _cross3(_cross3(pts_a[1], pts_b[2]), _cross3(pts_a[2], pts_b[1]))
    m20 = _cross3(_cross3(pts_a[2], pts_b[0]), _cross3(pts_a[0], pts_b[2]))

    det = sp.Matrix([list(m01), list(m12), list(m20)]).det()
    return sp.expand(det)
